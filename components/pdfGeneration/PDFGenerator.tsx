// PDFGenerator.tsx
import React from "react";
import jsPDF from "jspdf";
import "jspdf-autotable";
import Duty from "../duty/Duty";
import Trip from "../trip/Trip";
import DutyInfo from "../duty/DutyInfo";
import { Button, View } from "react-native";
import { OverTimeCalculationResult } from "../allowancecalculation/overtimeAllowance";

interface PDFGeneratorProps {
  duties: Duty[];
  designation: string;
  payBand: string;
  level: string;
  rateOfPay: number;
  selectedMonth: string;
  totalKilometers: number;
  mileage: number;
  nightDutyAllowance: number;
  nationalHolidayAllowance: number;
  leaveMileageAllowance: number;
  overTimeAllowance: number;
  dearnessAllowance: number;
  startDate: string;
  progressiveDutyHours: number;
  endDate: string;
  grandTotalAllowance:number;
  daysInMonth: number;
  overtimeResult: OverTimeCalculationResult | null;
}

const PDFGenerator: React.FC<PDFGeneratorProps> = ({
  duties,
  designation,
  payBand,
  level,
  rateOfPay,
  selectedMonth,
  totalKilometers,
  mileage,
  nightDutyAllowance,
  nationalHolidayAllowance,
  leaveMileageAllowance,
  overTimeAllowance,
  grandTotalAllowance,
  dearnessAllowance,
  startDate,
  progressiveDutyHours,
  endDate,
  daysInMonth,
  overtimeResult,
}) => {
  const generatePDF = () => {
    const doc = new jsPDF(); // Set portrait orientation (default)
    const footerText =
      "This is generated by Allowance Calculator an Platform by Feyntech Optimization Solutions Pvt. Ltd.";

    // Add header row
    const headerData = [
      {
        content: "Designation",
        colSpan: 1,
        styles: {
          fontStyle: "bold",
          fillColor: [200, 230, 245],
          textColor: [0, 0, 0],
        },
      },
      {
        content: designation,
        colSpan: 1,
        styles: {
          fontStyle: "bold",
          fillColor: [200, 230, 245],
          textColor: [0, 0, 0],
        },
      },
      {
        content: " | ",
        colSpan: 1,
        styles: {
          fontStyle: "bold",
          fillColor: [200, 230, 245],
          textColor: [0, 0, 0],
        },
      },
      {
        content: "Pay Band",
        colSpan: 1,
        styles: {
          fontStyle: "bold",
          fillColor: [200, 230, 245],
          textColor: [0, 0, 0],
        },
      },
      {
        content: payBand,
        colSpan: 1,
        styles: {
          fontStyle: "bold",
          fillColor: [200, 230, 245],
          textColor: [0, 0, 0],
        },
      },
      {
        content: " | ",
        colSpan: 1,
        styles: {
          fontStyle: "bold",
          fillColor: [200, 230, 245],
          textColor: [0, 0, 0],
        },
      },
      {
        content: "Level",
        colSpan: 1,
        styles: {
          fontStyle: "bold",
          fillColor: [200, 230, 245],
          textColor: [0, 0, 0],
        },
      },
      {
        content: level,
        colSpan: 1,
        styles: {
          fontStyle: "bold",
          fillColor: [200, 230, 245],
          textColor: [0, 0, 0],
        },
      },
      {
        content: " | ",
        colSpan: 1,
        styles: {
          fontStyle: "bold",
          fillColor: [200, 230, 245],
          textColor: [0, 0, 0],
        },
      },
      {
        content: "Rate of Pay",
        colSpan: 1,
        styles: {
          fontStyle: "bold",
          fillColor: [200, 230, 245],
          textColor: [0, 0, 0],
        },
      },
      {
        content: rateOfPay,
        colSpan: 1,
        styles: {
          fontStyle: "bold",
          fillColor: [200, 230, 245],
          textColor: [0, 0, 0],
        },
      },
      {
        content: " | ",
        colSpan: 1,
        styles: {
          fontStyle: "bold",
          fillColor: [200, 230, 245],
          textColor: [0, 0, 0],
        },
      },
      {
        content: "Selected Month",
        colSpan: 1,
        styles: {
          fontStyle: "bold",
          fillColor: [200, 230, 245],
          textColor: [0, 0, 0],
        },
      },
      {
        content: selectedMonth,
        colSpan: 1,
        styles: {
          fontStyle: "bold",
          fillColor: [200, 230, 245],
          textColor: [0, 0, 0],
        },
      },
    ];

    doc.setFontSize(8);
    doc.text(
      footerText,
      doc.internal.pageSize.getWidth() -
        doc.getStringUnitWidth(footerText) -
        10,
      doc.internal.pageSize.getHeight() - 10,
      { align: "right" }
    );

    // Render header row
    doc.autoTable({
      head: [headerData],
      theme: "grid",
      styles: { fontSize: 8, halign: "left" },
      margin: { top: 10, bottom: 10 },
    });

    let currentYPosition = doc.lastAutoTable.finalY + 10; // Track the current y position

    duties.forEach((duty, dutyIndex) => {
      doc.setFontSize(9);
      doc.text(`Duty ${dutyIndex + 1}`, 14, currentYPosition);
      currentYPosition += 5; // Add some space between the duty header and table

      // Trip header and data
      const tripTable = [
        [
          "Date",
          "Type of Work",
          "Train No.",
          "Source",
          "Dest.",
          "Dep. Time",
          "Arr. Time",
          "Distance",
          "Duty Hours",
          "km earned",
          "Remarks",
        ],
        ...duty.trips.map((trip) => [
          trip.date,
          trip.typeOfWork,
          trip.trainNumber,
          trip.sourceStation,
          trip.destinationStation,
          trip.arrivalTime,
          trip.departureTime,
          trip.distance.toFixed(2).toString(),
          trip.dutyHours,
          trip.allowance.toString(),
          trip.remarks,
        ]),
      ];

      doc.autoTable({
        head: [tripTable[0]], // Use the first row as the header
        body: tripTable.slice(1), // Use the remaining rows as the body
        theme: "grid",
        styles: { fontSize: 8 },
        startY: currentYPosition, // Start the table at the current y position
      });

      currentYPosition = doc.lastAutoTable.finalY + 2; // Update the current y position

      // DutyInfo
      const dutyInfoData = [
        [
          {
            content: "Sign In",
            colSpan: 1,
          },
          {
            content: duty.signIn
            ? new Date(duty.signIn).toLocaleString("en-GB", {
                day: "2-digit",
                month: "2-digit",
                year: "numeric",
                hour: "2-digit",
                minute: "2-digit",
              })
            : "-",
          colSpan: 1,
          },
          {
            content: "Sign Off",
            colSpan: 1,
          },
          {
            content: duty.signOff
            ? new Date(duty.signOff).toLocaleString("en-GB", {
                day: "2-digit",
                month: "2-digit",
                year: "numeric",
                hour: "2-digit",
                minute: "2-digit",
              })
            : "-",
          colSpan: 1,
          },
          {
            content: "KM earned:",
            colSpan: 1,
          },
          {
            content: `Rs. ${duty.calculateTotalAllowance().toFixed(2)}`,
            colSpan: 1,
          },
          {
            content: "Total Distance:",
            colSpan: 1,
          },
          {
            content: `${duty.calculateTotalDistance().toFixed(2)} km`,
            colSpan: 1,
          },
          {
            content: "Duty Hours",
            colSpan: 1,
          },
          {
            content: `${duty.dutyHours.toFixed(2)} H`,
            colSpan: 1,
          },
          {
            content: "Night Duty Hours :",
            colSpan: 1,
          },
          {
            content: `${duty.nightDutyHours.toFixed(2)} H`,
            colSpan: 1,
          },
        ],
        [
          {
            content: "Progressive Duty Hours",
            colSpan: 2,
          },
          {
            content: `${duty.progressiveDutyHours.toFixed(2)} H`,
            colSpan: 2,
          },
          {
            content: "OSDA",
            colSpan: 2,
          },
          {
            content: duty.isOSDA ? "Yes" : "No",
            colSpan: 2,
          },
          {
            content: "RRA",
            colSpan: 2,
          },
          {
            content: duty.isRRA ? "Yes" : "No",
            colSpan: 2,
          },
        ],
      ];

      doc.autoTable({
        head: [],
        body: dutyInfoData,
        theme: "grid",
        styles: { fontSize: 8 },
        startY: currentYPosition, // Start the table at the current y position
      });

      currentYPosition = doc.lastAutoTable.finalY + 10; // Update the current y position
    });

    // Add summary block data and overtime result


    currentYPosition = doc.lastAutoTable.finalY + 10; // Update the current y position

    if (overtimeResult) {
      const overtimeResultData = [
        [
          { content: "Fortnight", colSpan: 1, styles: { fontStyle: "bold" } },
          { content: "Start Date", colSpan: 1, styles: { fontStyle: "bold" } },
          { content: "End Date", colSpan: 1, styles: { fontStyle: "bold" } },
          {
            content: "Overtime Hours",
            colSpan: 1,
            styles: { fontStyle: "bold" },
          },
          {
            content: "Overtime Minutes",
            colSpan: 1,
            styles: { fontStyle: "bold" },
          },
          {
            content: "Overtime Unit",
            colSpan: 1,
            styles: { fontStyle: "bold" },
          },
        ],
        [
          { content: "First Fortnight", colSpan: 1 },
          {
            content:
              overtimeResult.firstFortnight?.startDate.toDateString() || "-",
            colSpan: 1,
          },
          {
            content:
              overtimeResult.firstFortnight?.endDate.toDateString() || "-",
            colSpan: 1,
          },
          {
            content:
              overtimeResult.firstFortnight?.overtimeHours.toString() || "-",
            colSpan: 1,
          },
          {
            content:
              overtimeResult.firstFortnight?.overtimeMinutes.toString() || "-",
            colSpan: 1,
          },
          {
            content:
              overtimeResult.firstFortnight?.overtimeUnit.toString() || "-",
            colSpan: 1,
          },
        ],
        [
          { content: "Second Fortnight", colSpan: 1 },
          {
            content:
              overtimeResult.secondFortnight?.startDate.toDateString() || "-",
            colSpan: 1,
          },
          {
            content:
              overtimeResult.secondFortnight?.endDate.toDateString() || "-",
            colSpan: 1,
          },
          {
            content:
              overtimeResult.secondFortnight?.overtimeHours.toString() || "-",
            colSpan: 1,
          },
          {
            content:
              overtimeResult.secondFortnight?.overtimeMinutes.toString() || "-",
            colSpan: 1,
          },
          {
            content:
              overtimeResult.secondFortnight?.overtimeUnit.toString() || "-",
            colSpan: 1,
          },
        ],
      ];

      doc.autoTable({
        head: [
          [
            {
              content: "Overtime Calculation Result",
              colSpan: 6,
              styles: {
                fontStyle: "bold",
                fillColor: [200, 230, 245],
                textColor: [0, 0, 0],
              },
            },
          ],
        ],
        body: overtimeResultData,
        theme: "grid",
        styles: { fontSize: 8 },
        startY: currentYPosition, // Start the table at the current y position
      });
    
      currentYPosition = doc.lastAutoTable.finalY + 10; // Update the current y position
    }

    const summaryBlockData = [
      [
        {
          content: "Total Kilometers:",
          colSpan: 1,
          styles: { fontStyle: "bold" },
        },
        {
          content: totalKilometers ? `${totalKilometers.toFixed(2)}` : "-",
          colSpan: 1,
        },
      ],
      [
        { content: "Mileage:", colSpan: 1, styles: { fontStyle: "bold" } },
        { content: mileage ? `Rs. ${mileage.toFixed(2)}` : "-", colSpan: 1 },
      ],
      [
        {
          content: "Night Duty Allowance:",
          colSpan: 1,
          styles: { fontStyle: "bold" },
        },
        {
          content: nightDutyAllowance
            ? `Rs. ${nightDutyAllowance.toFixed(2)}`
            : "-",
          colSpan: 1,
        },
      ],

      [
        {
          content: "Leave Mileage Allowance:",
          colSpan: 1,
          styles: { fontStyle: "bold" },
        },
        {
          content: leaveMileageAllowance
            ? `Rs. ${leaveMileageAllowance.toFixed(2)}`
            : "-",
          colSpan: 1,
        },
      ],
      [
        {
          content: "Dearness Allowance:",
          colSpan: 1,
          styles: { fontStyle: "bold" },
        },
        {
          content: dearnessAllowance
            ? `Rs. ${dearnessAllowance.toFixed(2)}`
            : "-",
          colSpan: 1,
        },
      ],
      [
        {
          content: "Progressive Duty Hours:",
          colSpan: 1,
          styles: { fontStyle: "bold" },
        },
        {
          content: progressiveDutyHours
            ? `${progressiveDutyHours.toFixed(2)} H`
            : "-",
          colSpan: 1,
        },
      ],
      [
        {
          content: "Grand Total Allowance:",
          colSpan: 1,
          styles: { fontStyle: "bold" },
        },
        {
          content: grandTotalAllowance
            ? `Rs. ${grandTotalAllowance.toFixed(2)}`
            : "-",
          colSpan: 1,
        },
      ],
    ];

    doc.autoTable({
      head: [
        [
          {
            content: "Summary Block",
            colSpan: 2,
            styles: {
              fontStyle: "bold",
              fillColor: [200, 230, 245],
              textColor: [0, 0, 0],
            },
          },
        ],
      ],
      body: summaryBlockData,
      theme: "grid",
      styles: { fontSize: 8 },
      startY: currentYPosition, // Start the table at the current y position
    });

    doc.save("duty-report.pdf");
  };
  return (
    <View>
      <Button title="Generate PDF" onPress={generatePDF} />
    </View>
  );
};
export default PDFGenerator;
